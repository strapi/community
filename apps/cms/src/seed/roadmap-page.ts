import type { Core } from "@strapi/strapi";

const uid = "api::overview-page.overview-page" as const;
const itemUid = "api::roadmap-item.roadmap-item" as const;
const SLUG = "roadmap";

/**
 * Gives roadmap items their own URL under the roadmap page, so a shared item
 * link resolves through the web app's catch-all route (it renders the
 * roadmap page with that item's dialog open). Created once, then managed in
 * the webtools settings; existing items get their alias when it's created,
 * new ones when the sync creates them.
 */
async function seedItemUrlPattern(strapi: Core.Strapi): Promise<void> {
  const existing = await strapi
    .documents("plugin::webtools.url-pattern")
    .findFirst({ filters: { contenttype: itemUid } });

  if (existing) return;

  await strapi.documents("plugin::webtools.url-pattern").create({
    data: {
      contenttype: itemUid,
      pattern: `/${SLUG}/[slug]`,
      languages: [],
    },
  });

  const count = await strapi
    .plugin("webtools")
    .service("bulk-generate")
    .generateUrlAliases({ types: [itemUid], generationType: "only_missing" });

  strapi.log.info(
    `[seed] Created roadmap item URL pattern, generated ${count} aliases`,
  );
}

/**
 * Creates the `/roadmap` overview page with its roadmap section, once.
 * After that it's edited in the admin panel. A deleted page is recreated on
 * the next boot, so unpublish it instead to take it offline.
 *
 * The URL alias is generated by webtools from the overview page URL pattern.
 */
export async function seedRoadmapPage(strapi: Core.Strapi): Promise<void> {
  await seedItemUrlPattern(strapi);

  const existing = await strapi.documents(uid).findFirst({
    filters: { slug: SLUG },
    status: "draft",
  });

  if (existing) return;

  const page = await strapi.documents(uid).create({
    status: "published",
    data: {
      title: "Roadmap",
      slug: SLUG,
      description:
        "Follow what the core team is planning, building and shipping. Where there is one, each item links to its GitHub issue and its feedback board thread, so you can upvote, comment and follow the work in the open.",
      seo: {
        metaTitle: "Roadmap: What We're Building Next",
        metaDescription:
          "See what the Strapi core team is planning, building and shipping. Follow each item on GitHub and vote for what matters to you on the feedback board.",
        keywords:
          "strapi roadmap, strapi releases, strapi features, strapi changelog",
      },
      sections: [{ __component: "sections.roadmap", show_feedback_link: true }],
    },
    populate: { url_alias: true },
  });

  // biome-ignore lint/suspicious/noExplicitAny: url_alias is set by webtools
  const paths = ((page as any).url_alias ?? []).map(
    (alias: { url_path: string }) => alias.url_path,
  );
  if (!paths.includes(`/${SLUG}`)) {
    strapi.log.warn(
      `[seed] Roadmap page got URL alias ${paths.join(", ") || "(none)"} instead of /${SLUG}; set it in the admin panel`,
    );
  }

  strapi.log.info("[seed] Created roadmap overview page");
}
